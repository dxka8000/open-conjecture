mkdirSync("records/collatz", { recursive: true });
let created = 0;
const put = (rec) => {
  const f = `records/collatz/${rec.id}.json`;
  if (existsSync(f)) return;
  writeFileSync(f, JSON.stringify(rec, null, 2) + "\n");
  created++;
};
